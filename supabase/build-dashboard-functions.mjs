/**
 * Makes single-file copies of the edge functions for deploying from the
 * Supabase dashboard (Edge Functions → function → Code → Deploy), which
 * can't follow imports like "../_shared/plan.ts".
 *
 *   node supabase/build-dashboard-functions.mjs
 *
 * Writes supabase/dashboard-functions/<name>.ts — paste each one into the
 * function of the same name in the dashboard. Don't edit those files by hand;
 * edit supabase/functions/ and run this again (CI checks they're up to date).
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, 'functions');
const OUT = join(here, 'dashboard-functions');

const RUNTIME_IMPORT = /^import\s+["']jsr:@supabase\/functions-js\/edge-runtime\.d\.ts["'];?\s*$/m;
const RELATIVE_IMPORT = /^import\s+(?:type\s+)?\{([\s\S]*?)\}\s+from\s+["'](\.{1,2}\/[^"']+)["'];?\s*$/gm;
const DECL = /^(?:export\s+)?(?:async\s+)?(?:function|const|let|var|class|interface|type)\s+([A-Za-z_$][\w$]*)/gm;

const declaredNames = (code) => new Set(Array.from(code.matchAll(DECL), (m) => m[1]));

function inline(file, taken, seen) {
  let code = readFileSync(file, 'utf8');
  const parts = [];
  code = code.replace(RELATIVE_IMPORT, (_all, _names, spec) => {
    const target = resolve(dirname(file), spec);
    if (seen.has(target)) return '';
    seen.add(target);
    const inner = inline(target, taken, seen);
    // A shared module can itself import another shared module: put that one first.
    let mod = typeof inner === 'string' ? inner : `${inner.parts.join('\n')}\n${inner.code}`;
    mod = mod.replace(RUNTIME_IMPORT, '').replace(/^export\s+(?=(async\s+)?(function|const|let|var|class|interface|type)\b)/gm, '');
    // Rename this module's top-level names that clash with the function's own names
    // (shared modules are written not to clash with each other).
    for (const name of declaredNames(mod)) {
      if (taken.has(name)) mod = mod.replace(new RegExp(`(?<![\\w$.])${name.replace('$', '\\$')}(?![\\w$])`, 'g'), `${name}_shared`);
    }
    parts.push(`// ── inlined from ${spec.replace(/^\.\.\//, 'supabase/functions/').replace(/^\.\//, '')} ──\n${mod.trim()}\n`);
    return '';
  });
  return parts.length ? { code, parts } : code;
}

mkdirSync(OUT, { recursive: true });
const written = [];
for (const name of readdirSync(SRC).sort()) {
  const dir = join(SRC, name);
  const entry = join(dir, 'index.ts');
  if (name.startsWith('_') || !statSync(dir).isDirectory() || !existsSync(entry)) continue;
  const main = readFileSync(entry, 'utf8');
  const taken = declaredNames(main);
  const result = inline(entry, taken, new Set());
  let body;
  if (typeof result === 'string') {
    body = result;
  } else {
    const hasRuntime = RUNTIME_IMPORT.test(result.code);
    const rest = result.code.replace(RUNTIME_IMPORT, '').replace(/^\s*\n/, '');
    body = `${hasRuntime ? 'import "jsr:@supabase/functions-js/edge-runtime.d.ts";\n\n' : ''}${result.parts.join('\n')}\n// ── ${name} ──\n${rest}`;
  }
  const header = `// Single-file copy of supabase/functions/${name}/index.ts for deploying from the\n// Supabase dashboard. Generated by supabase/build-dashboard-functions.mjs — do not edit.\n\n`;
  writeFileSync(join(OUT, `${name}.ts`), header + body.replace(/\n{3,}/g, '\n\n'));
  written.push(name);
}
console.log(`Wrote ${written.length} functions to supabase/dashboard-functions: ${written.join(', ')}`);
